export const SUPPORTED_LOCALES = [
  { code: 'en', label: 'English',  flag: '🇬🇧' },
  { code: 'pl', label: 'Polski',   flag: '🇵🇱' },
  { code: 'de', label: 'Deutsch',  flag: '🇩🇪' },
];

const LS_KEY = 'mv_locale';
let currentLocale = null;

function detectBrowserLocale() {
  if (typeof navigator === 'undefined') return 'en';
  // navigator.languages is preferred — ordered list. Fall back to language.
  const candidates = (navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || 'en']);
  for (const lang of candidates) {
    const code = String(lang || '').toLowerCase().split('-')[0];
    if (TRANSLATIONS[code]) return code;
  }
  return 'en';
}

export function getLocale() {
  if (currentLocale) return currentLocale;
  if (typeof localStorage !== 'undefined') {
    const stored = localStorage.getItem(LS_KEY);
    if (stored && TRANSLATIONS[stored]) {
      currentLocale = stored;
      return currentLocale;
    }
  }
  currentLocale = detectBrowserLocale();
  return currentLocale;
}

export function setLocale(locale) {
  if (!TRANSLATIONS[locale]) return;
  currentLocale = locale;
  try { localStorage.setItem(LS_KEY, locale); } catch {}
  // Notify subscribed components to re-render
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('mv:locale-changed', { detail: { locale } }));
  }
}

// Lookup a key in the active dictionary. Falls back to English, then to
// the key name. Optional second arg substitutes {placeholders}.
export function t(key, vars) {
  const locale = getLocale();
  const dict = TRANSLATIONS[locale] || TRANSLATIONS.en;
  let str = dict[key] || TRANSLATIONS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
    }
  }
  return str;
}

// ── Plural-aware lookup ───────────────────────────────────────
// English has 2 plural forms (one / other), Polish has 4 (one /
// few / many / other), German has 2. JavaScript ships
// Intl.PluralRules which picks the right CLDR category for any
// locale. Callers store keys as `<base>.one`, `<base>.few`,
// `<base>.many`, `<base>.other` and we resolve at render time.
//
//   tn(3, 'watchlist.album', { n: 3 })
//     pl → 'watchlist.album.few'  → '3 albumy'
//     en → 'watchlist.album.other' → '3 albums'
//
// Falls back through: <base>.<category> → <base>.other → English
// → bare key. Same {placeholder} substitution as t().
export function tn(count, base, vars) {
  const locale = getLocale();
  let category = 'other';
  try { category = new Intl.PluralRules(locale).select(count); } catch {}
  const dict = TRANSLATIONS[locale] || TRANSLATIONS.en;
  const en   = TRANSLATIONS.en;
  let str = dict[base + '.' + category]
         || dict[base + '.other']
         || en[base + '.' + category]
         || en[base + '.other']
         || base;
  const allVars = { n: count, ...(vars || {}) };
  for (const [k, v] of Object.entries(allVars)) {
    str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
  }
  return str;
}

// React hook — re-renders component when locale changes
export function useT() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const handler = () => setTick(x => x + 1);
    window.addEventListener('mv:locale-changed', handler);
    return () => window.removeEventListener('mv:locale-changed', handler);
  }, []);
  return t;
}

// Returns the active locale code as a stable React state — useful when
// the picker UI itself needs to mark the current option.
export function useLocale() {
  const [locale, setLocaleState] = useState(() => getLocale());
  useEffect(() => {
    const handler = (e) => setLocaleState(e.detail?.locale || getLocale());
    window.addEventListener('mv:locale-changed', handler);
    return () => window.removeEventListener('mv:locale-changed', handler);
  }, []);
  return locale;
}
